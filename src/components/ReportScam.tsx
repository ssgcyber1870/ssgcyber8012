import { useState } from 'react';
import {
  Siren, CheckCircle2, FileDown, MessageCircle, UploadCloud, Loader2, PartyPopper,
} from 'lucide-react';
import { supabase } from '../lib/supabase';
import { COUNTRIES, agenciesForCountry } from '../lib/data';
import { Reveal, SectionHeading } from './ui';

const SCAM_TYPES = [
  'Romance', 'Crypto / Investment', 'Bank / Phishing', 'Fake Job',
  'Hacking / Blackmail', 'Sextortion', 'Online Shopping', 'Other',
];
const PLATFORMS = ['WhatsApp', 'Telegram', 'Instagram', 'Facebook', 'Email', 'Website', 'Phone Call'];

interface FormState {
  fullName: string;
  email: string;
  phone: string;
  country: string;
  age: string;
  scamType: string;
  platform: string;
  amount: string;
  currency: string;
  scamDate: string;
  scammerInfo: string;
  details: string;
  anonymousShare: boolean;
}

const INITIAL: FormState = {
  fullName: '', email: '', phone: '', country: '', age: '',
  scamType: '', platform: '', amount: '', currency: 'USD',
  scamDate: '', scammerInfo: '', details: '', anonymousShare: false,
};

function validate(f: FormState, evidence: File | null): Record<string, string> {
  const errors: Record<string, string> = {};
  if (!f.fullName.trim()) errors.fullName = 'Please enter your full name.';
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(f.email)) errors.email = 'Please enter a valid email address.';
  if (!f.phone.trim()) errors.phone = 'Please enter a phone or WhatsApp number.';
  if (!f.country) errors.country = 'Please select your country.';
  if (!f.scamType) errors.scamType = 'Please select the type of scam.';
  if (!f.platform) errors.platform = 'Please select where the scam happened.';
  if (!f.details.trim() || f.details.trim().length < 30) errors.details = 'Please describe what happened (at least 30 characters).';
  if (f.age && (Number(f.age) < 1 || Number(f.age) > 120)) errors.age = 'Please enter a valid age.';
  if (evidence && evidence.size > 5 * 1024 * 1024) errors.evidence = 'File is too large. Maximum size is 5 MB.';
  return errors;
}

function downloadPdfReport(f: FormState, caseId: string) {
  const rows: [string, string][] = [
    ['Case ID', caseId],
    ['Full Name', f.fullName],
    ['Email', f.email],
    ['Phone / WhatsApp', f.phone],
    ['Country', f.country],
    ['Age', f.age || '—'],
    ['Scam Type', f.scamType],
    ['Platform', f.platform],
    ['Amount Lost', f.amount ? `${f.currency} ${Number(f.amount).toLocaleString()}` : 'Not specified'],
    ['Date of Scam', f.scamDate || '—'],
    ['Scammer Info (name / number / link / wallet)', f.scammerInfo || '—'],
    ['Consent to share anonymously', f.anonymousShare ? 'Yes' : 'No'],
    ['', ''],
    ['What Happened', f.details],
  ];
  const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const body = rows
    .map(([k, v]) => `<tr><td style="padding:6px 10px;font-weight:700;background:#F4F6F8;width:40%">${esc(k)}</td><td style="padding:6px 10px">${esc(v)}</td></tr>`)
    .join('');
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>SCG Report ${esc(caseId)}</title></head>
<body style="font-family:Arial,sans-serif;color:#1A1A1A;margin:32px">
<h1 style="color:#0A1931;margin-bottom:2px">STOP CYBERCRIME GLOBALLY</h1>
<p style="color:#FF2D2D;font-weight:700;margin-top:0">Scam Report — ${esc(caseId)}</p>
<table style="border-collapse:collapse;width:100%;font-size:13px" border="1" cellpadding="0" cellspacing="0">${body}</table>
<p style="margin-top:24px;font-size:11px;color:#666">Confidential report generated by SCG Global. Keep your Case ID safe — quote it in all follow-ups. Helpline: +234-XXX-XXX-XXXX</p>
</body></html>`;
  const win = window.open('', '_blank');
  if (win) {
    win.document.write(html);
    win.document.close();
    win.focus();
    setTimeout(() => win.print(), 400);
  }
}

const NEXT_STEPS = [
  'Save your Case ID — quote it in every email or call.',
  'Our triage team reviews your report within 24 hours.',
  'A case officer contacts you (discreetly) with next steps.',
  'If money was lost, we prepare bank dispute / EFCC / FBI IC3 filings immediately.',
];

export default function ReportScam() {
  const [form, setForm] = useState<FormState>(INITIAL);
  const [evidence, setEvidence] = useState<File | null>(null);
  const [errors, setErrors] = useState<Record<string, string>>({});
  const [submitting, setSubmitting] = useState(false);
  const [submitError, setSubmitError] = useState('');
  const [caseId, setCaseId] = useState('');

  const set = (key: keyof FormState) => (e: React.ChangeEvent<HTMLInputElement | HTMLSelectElement | HTMLTextAreaElement>) => {
    const value = e.target.type === 'checkbox' ? (e.target as HTMLInputElement).checked : e.target.value;
    setForm((f) => ({ ...f, [key]: value }));
    setErrors((er) => ({ ...er, [key]: '' }));
  };

  const onSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setSubmitError('');
    const errs = validate(form, evidence);
    setErrors(errs);
    if (Object.keys(errs).length > 0) return;

    setSubmitting(true);
    const { data, error } = await supabase
      .from('scam_reports')
      .insert({
        full_name: form.fullName.trim(),
        email: form.email.trim(),
        phone: form.phone.trim(),
        country: form.country,
        age: form.age ? Number(form.age) : null,
        scam_type: form.scamType,
        platform: form.platform,
        amount_lost: form.amount ? Number(form.amount) : 0,
        currency: form.currency,
        scam_date: form.scamDate || null,
        scammer_info: form.scammerInfo.trim() || null,
        details: form.details.trim(),
        anonymous_share: form.anonymousShare,
        evidence_name: evidence?.name ?? null,
      })
      .select('case_id')
      .single();

    setSubmitting(false);
    if (error || !data) {
      setSubmitError('Something went wrong submitting your report. Please try again, or call our 24/7 helpline.');
      return;
    }
    setCaseId(data.case_id);
    window.scrollTo({ top: document.getElementById('report')?.offsetTop ?? 0, behavior: 'smooth' });
  };

  const reset = () => {
    setForm(INITIAL);
    setEvidence(null);
    setCaseId('');
  };

  const errCls = (key: string) => `${errors[key] ? 'input-invalid ' : ''}field-input`;

  const matchedAgencies = form.country ? agenciesForCountry(form.country) : [];

  return (
    <section id="report" className="bg-light py-20 dark:bg-navy-800 sm:py-24">
      <div className="container-x">
        <SectionHeading
          label="Report a Scam"
          title="Report in 2 Minutes. Get a Real Case ID."
          subtitle="Every report strengthens the global picture and unlocks free help for you. Confidential by default."
        />

        <Reveal>
          <div className="mx-auto mt-12 max-w-3xl">
            {caseId ? (
              /* ---------- SUCCESS SCREEN ---------- */
              <div className="card p-8 text-center sm:p-10">
                <span className="mx-auto grid h-16 w-16 place-items-center rounded-full bg-success-500/10">
                  <PartyPopper className="h-8 w-8 text-success-500" />
                </span>
                <h3 className="mt-5 text-2xl font-bold text-navy-700 dark:text-white">Report Received. Thank You.</h3>
                <p className="mt-2 text-sm text-gray-600 dark:text-gray-400">
                  Your report is confidential. Here is your case ID — keep it safe:
                </p>
                <p className="mx-auto mt-5 w-fit rounded-xl2 border-2 border-dashed border-brand-500/40 bg-brand-50 px-8 py-4 font-mono text-3xl font-bold tracking-wider text-brand-600 dark:bg-brand-500/10">
                  {caseId}
                </p>

                <div className="mx-auto mt-8 max-w-md text-left">
                  <h4 className="text-sm font-bold text-navy-700 dark:text-white">What happens next:</h4>
                  <ol className="mt-3 space-y-3">
                    {NEXT_STEPS.map((s, i) => (
                      <li key={i} className="flex items-start gap-3 text-sm text-gray-600 dark:text-gray-400">
                        <CheckCircle2 className="mt-0.5 h-4 w-4 shrink-0 text-success-500" />
                        {s}
                      </li>
                    ))}
                  </ol>
                </div>

                <div className="mt-8 flex flex-wrap justify-center gap-3">
                  <button onClick={() => downloadPdfReport(form, caseId)} className="btn-outline">
                    <FileDown className="h-4 w-4" /> Download PDF Report
                  </button>
                  <a
                    href={`https://wa.me/234000000000?text=${encodeURIComponent(`Hello SCG, my case ID is ${caseId}. I just reported a scam.`)}`}
                    target="_blank"
                    rel="noreferrer"
                    className="btn-red"
                  >
                    <MessageCircle className="h-4 w-4" /> Follow Up on WhatsApp
                  </a>
                </div>
                <button onClick={reset} className="mt-6 text-xs font-medium text-gray-500 underline hover:text-brand-500">
                  Report another scam
                </button>
              </div>
            ) : (
              /* ---------- FORM ---------- */
              <form onSubmit={onSubmit} noValidate className="card p-6 sm:p-10">
                <div className="flex items-center gap-3 border-b border-gray-100 pb-6 dark:border-white/10">
                  <span className="grid h-12 w-12 place-items-center rounded-xl2 bg-brand-500/10">
                    <Siren className="h-6 w-6 text-brand-500" />
                  </span>
                  <div>
                    <h3 className="text-lg font-bold text-navy-700 dark:text-white">Scam Report Form</h3>
                    <p className="text-xs text-gray-500 dark:text-gray-400">Fields marked with an asterisk are required.</p>
                  </div>
                </div>

                <div className="mt-8 grid gap-5 sm:grid-cols-2">
                  <div>
                    <label htmlFor="r-name" className="field-label">Full Name *</label>
                    <input id="r-name" className={errCls('fullName')} value={form.fullName} onChange={set('fullName')} placeholder="Chidi Okonkwo" />
                    {errors.fullName && <p className="field-error" role="alert">{errors.fullName}</p>}
                  </div>
                  <div>
                    <label htmlFor="r-email" className="field-label">Email *</label>
                    <input id="r-email" type="email" className={errCls('email')} value={form.email} onChange={set('email')} placeholder="you@example.com" />
                    {errors.email && <p className="field-error" role="alert">{errors.email}</p>}
                  </div>
                  <div>
                    <label htmlFor="r-phone" className="field-label">WhatsApp / Phone *</label>
                    <input id="r-phone" type="tel" className={errCls('phone')} value={form.phone} onChange={set('phone')} placeholder="+234 800 000 0000" />
                    {errors.phone && <p className="field-error" role="alert">{errors.phone}</p>}
                  </div>
                  <div>
                    <label htmlFor="r-country" className="field-label">Country *</label>
                    <select id="r-country" className={errCls('country')} value={form.country} onChange={set('country')}>
                      <option value="">Select country…</option>
                      {COUNTRIES.map((c) => <option key={c} value={c}>{c}</option>)}
                    </select>
                    {errors.country && <p className="field-error" role="alert">{errors.country}</p>}
                    {matchedAgencies.length > 0 && (
                      <div
                        className="mt-3 rounded-xl2 border-l-4 border-gold-400 bg-gold-50 px-4 py-3 text-xs leading-relaxed text-navy-700 dark:bg-gold-400/10 dark:text-gray-200"
                        role="note"
                      >
                        <strong className="font-bold">For {form.country}, you should also report to:</strong>
                        <ul className="mt-1.5 space-y-1">
                          {matchedAgencies.map((a) => (
                            <li key={a.site}>
                              <a
                                href={`https://${a.site}`}
                                target="_blank"
                                rel="noreferrer"
                                className="font-semibold text-brand-600 underline underline-offset-2 hover:text-brand-700"
                              >
                                {a.name} — {a.site}
                              </a>
                            </li>
                          ))}
                        </ul>
                        <p className="mt-1.5">We will help you file this after you submit to SCG.</p>
                      </div>
                    )}
                  </div>
                  <div>
                    <label htmlFor="r-age" className="field-label">Age</label>
                    <input id="r-age" type="number" min={1} max={120} className={errCls('age')} value={form.age} onChange={set('age')} placeholder="Optional" />
                    {errors.age && <p className="field-error" role="alert">{errors.age}</p>}
                  </div>
                  <div>
                    <label htmlFor="r-type" className="field-label">Scam Type *</label>
                    <select id="r-type" className={errCls('scamType')} value={form.scamType} onChange={set('scamType')}>
                      <option value="">Select scam type…</option>
                      {SCAM_TYPES.map((t) => <option key={t} value={t}>{t}</option>)}
                    </select>
                    {errors.scamType && <p className="field-error" role="alert">{errors.scamType}</p>}
                  </div>
                  <div>
                    <label htmlFor="r-platform" className="field-label">Platform *</label>
                    <select id="r-platform" className={errCls('platform')} value={form.platform} onChange={set('platform')}>
                      <option value="">Select platform…</option>
                      {PLATFORMS.map((p) => <option key={p} value={p}>{p}</option>)}
                    </select>
                    {errors.platform && <p className="field-error" role="alert">{errors.platform}</p>}
                  </div>
                  <div>
                    <label htmlFor="r-amount" className="field-label">Amount Lost</label>
                    <div className="flex gap-2">
                      <select aria-label="Currency" className="field-input w-24" value={form.currency} onChange={set('currency')}>
                        <option value="USD">USD</option>
                        <option value="NGN">Naira</option>
                      </select>
                      <input id="r-amount" type="number" min={0} className={errCls('amount')} value={form.amount} onChange={set('amount')} placeholder="e.g. 1500" />
                    </div>
                  </div>
                  <div>
                    <label htmlFor="r-date" className="field-label">Date of Scam</label>
                    <input id="r-date" type="date" max={new Date().toISOString().split('T')[0]} className={errCls('scamDate')} value={form.scamDate} onChange={set('scamDate')} />
                  </div>
                  <div className="sm:col-span-2">
                    <label htmlFor="r-scammer" className="field-label">Scammer Name / Number / Link / Wallet Address</label>
                    <input id="r-scammer" className={errCls('scammerInfo')} value={form.scammerInfo} onChange={set('scammerInfo')} placeholder="Anything you have — a username, phone number, website link or wallet address" />
                  </div>
                  <div className="sm:col-span-2">
                    <label htmlFor="r-details" className="field-label">What Happened? *</label>
                    <textarea id="r-details" rows={5} className={errCls('details')} value={form.details} onChange={set('details')} placeholder="Describe the scam in your own words — dates, promises made, how they contacted you…" />
                    {errors.details && <p className="field-error" role="alert">{errors.details}</p>}
                  </div>
                  <div className="sm:col-span-2">
                    <label htmlFor="r-evidence" className="field-label">Upload Evidence (screenshot or PDF, max 5 MB)</label>
                    <label
                      htmlFor="r-evidence"
                      className="flex cursor-pointer items-center gap-3 rounded-xl2 border-2 border-dashed border-gray-200 bg-gray-50 px-4 py-4 text-sm text-gray-500 transition hover:border-brand-500/50 hover:bg-brand-50/50 dark:border-white/10 dark:bg-white/5 dark:text-gray-400"
                    >
                      <UploadCloud className="h-5 w-5 text-brand-500" />
                      {evidence ? <span className="font-medium text-navy-700 dark:text-white">{evidence.name}</span> : <span>Click to attach a file</span>}
                    </label>
                    <input
                      id="r-evidence"
                      type="file"
                      accept="image/*,.pdf"
                      className="sr-only"
                      onChange={(e) => {
                        setEvidence(e.target.files?.[0] ?? null);
                        setErrors((er) => ({ ...er, evidence: '' }));
                      }}
                    />
                    {errors.evidence && <p className="field-error" role="alert">{errors.evidence}</p>}
                  </div>
                  <div className="sm:col-span-2">
                    <label className="flex cursor-pointer items-start gap-3 text-sm text-gray-600 dark:text-gray-400">
                      <input
                        type="checkbox"
                        checked={form.anonymousShare}
                        onChange={set('anonymousShare')}
                        className="mt-0.5 h-4 w-4 rounded border-gray-300 text-brand-500 focus:ring-brand-500"
                      />
                      I agree to share my story anonymously for awareness (my name and contact details are never published).
                    </label>
                  </div>
                </div>

                {submitError && (
                  <p className="mt-5 rounded-xl2 bg-brand-50 px-4 py-3 text-sm font-medium text-brand-700 dark:bg-brand-500/10" role="alert">
                    {submitError}
                  </p>
                )}

                <button type="submit" disabled={submitting} className="btn-red mt-8 w-full py-4 text-base">
                  {submitting ? (
                    <><Loader2 className="h-5 w-5 animate-spin" /> Submitting securely…</>
                  ) : (
                    <><Siren className="h-5 w-5" /> SUBMIT REPORT — GET CASE ID</>
                  )}
                </button>
              </form>
            )}
          </div>
        </Reveal>
      </div>
    </section>
  );
}
